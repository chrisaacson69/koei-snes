#!/usr/bin/env python3
"""
Generate name<->number enums from a title's syscall/opcode name tables, so tools and
readers can use natural-language names instead of numbers.

    py -3 tools/gen_enums.py <title_dir>       # e.g. ../rot3k2-snes-decompiler
Reads <title_dir>/data/syscall_names.toml (id -> name) and emits
<title_dir>/data/enums.py  (SYSCALLS = {id: name}, plus reverse map) that the VM tools
import to render `hostcall sys_blit_rect` etc. Opcode names come from koei-snes
data/vm_opcode_names.toml (shared across titles).
"""
import os, re, sys


def parse_syscalls(path):
    """Pull id + name from the [[syscall]] blocks (no toml dep needed)."""
    out = {}
    cur_id = None
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        m = re.match(r"id\s*=\s*(0x[0-9A-Fa-f]+|\d+)", line)
        if m:
            cur_id = int(m.group(1), 0); continue
        m = re.match(r'name\s*=\s*"([^"]+)"', line)
        if m and cur_id is not None:
            out[cur_id] = m.group(1); cur_id = None
    return out


def main(argv):
    tdir = argv[1] if len(argv) > 1 else "."
    src = os.path.join(tdir, "data", "syscall_names.toml")
    sc = parse_syscalls(src)
    dst = os.path.join(tdir, "data", "enums.py")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("# AUTO-GENERATED by koei-snes/tools/gen_enums.py from syscall_names.toml.\n")
        f.write("# id -> natural-language syscall name (read syscalls by name, not number).\n\n")
        f.write("SYSCALLS = {\n")
        for i in sorted(sc):
            f.write("    0x%02X: %r,\n" % (i, sc[i]))
        f.write("}\n")
        f.write("SYSCALL_ID = {v: k for k, v in SYSCALLS.items()}\n")
    print("wrote %s (%d syscalls: %s ... %s)" %
          (dst, len(sc), sc.get(min(sc)), sc.get(max(sc))))


if __name__ == "__main__":
    main(sys.argv)
